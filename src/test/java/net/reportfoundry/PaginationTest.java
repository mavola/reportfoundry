package net.reportfoundry;

import org.apache.pdfbox.Loader;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

class PaginationTest {

    @Test
    void pageBreakShouldCreateSecondPage() throws Exception {
        byte[] pdf = ReportFoundry.forge()
                .title("First page")
                .text("Page one.")
                .pageBreak()
                .title("Second page")
                .text("Page two.")
                .toBytes();

        try (PDDocument document = Loader.loadPDF(pdf)) {
            assertEquals(2, document.getNumberOfPages());
        }
    }

    @Test
    void longContentShouldCreateMultiplePages() throws Exception {
        ReportForge report = ReportFoundry.forge().title("Pagination test");

        for (int i = 0; i < 150; i++) {
            report.text("This is line number " + i + " generated by ReportFoundry.");
        }

        byte[] pdf = report.toBytes();
        try (PDDocument document = Loader.loadPDF(pdf)) {
            assertTrue(document.getNumberOfPages() > 1);
        }
    }
}
